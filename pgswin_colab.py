present = set(alld.optim_method.unique())
rows = []
for a, b in COMPARISONS:
    if a not in present or b not in present: continue
    for kl in CLASS_NAMES:
        r = paired_seed_level_test(slevel, a, b, kl)
        bt = hierarchical_bootstrap(alld, a, b, kl)
        rows.append(dict(klass=kl, comparison=f"{a} vs {b}", **r, **bt))
stats = pd.DataFrame(rows)
stats["p_holm"], stats["p_bh_fdr"] = adjust_pvalues(stats["p_raw"].tolist())
stats["sig_holm"] = np.where(stats["p_holm"] < 0.05, "YES", "NO")

main = []
for kl in CLASS_NAMES:
    for m in ["baseline", "swin_bottleneck"] + [k for k in VARIANTS if k in present]:
        s = slevel[(slevel.optim_method == m) & (slevel.klass_name == kl)]
        if len(s): main.append(dict(klass=kl, method=m, n=s.seed.nunique(),
                                    dice=f"{s.seed_mean_dice.mean():.4f} +- {s.seed_mean_dice.std(ddof=1):.4f}",
                                    hd95=f"{s.seed_mean_hd95.mean():.3f}", assd=f"{s.seed_mean_assd.mean():.4f}"))
main = pd.DataFrame(main)
print(main.to_string(index=False))
print()
print(stats[["klass", "comparison", "mean_delta", "ci95_low", "ci95_high", "cohens_d", "p_raw", "p_holm", "sig_holm"]]
      .to_string(index=False))
