def build_pg(cfg, v):
    return PGSwinUNet3D(cfg, use_swin=v["use_swin"], use_proto=v["use_proto"], deep_sup=v["deep_sup"])


@torch.no_grad()
def ema_update(ema, model, step, decay=EMA_DECAY):
    d = min(decay, (1 + step) / (10 + step))
    for pe, p in zip(ema.parameters(), model.parameters()):
        pe.mul_(d).add_(p.detach(), alpha=1 - d)
    for be, b in zip(ema.buffers(), model.buffers()):
        be.copy_(b)


@torch.no_grad()
def val_dice_of(m, loader):
    m.eval(); out = []
    for imgs, masks, _, _, _ in loader:
        imgs, masks = imgs.to(DEVICE), masks.to(DEVICE)
        preds = (torch.sigmoid(m(imgs)) > 0.5).float()
        inter = (preds * masks).sum(dim=(2, 3, 4))
        card = (preds + masks).sum(dim=(2, 3, 4)) + 1e-5
        out.append(((2.0 * inter + 1e-5) / card).mean().item())
    return float(np.mean(out))


def train_one_v2(model, loaders, epochs, loss_fn, run_dir, cfg, v, tag=""):
    os.makedirs(run_dir, exist_ok=True)
    last_path, best_path = os.path.join(run_dir, "last.pt"), os.path.join(run_dir, "best.pt")
    model = model.to(DEVICE)
    ema = copy.deepcopy(model).eval() if v["ema"] else None
    eval_model = ema if v["ema"] else model            # the model that is validated / saved / tested
    opt = optim.AdamW(model.parameters(), lr=cfg["lr"], weight_decay=cfg["weight_decay"])
    sched = CosineAnnealingLR(opt, T_max=epochs)
    start_epoch, best_val, best_epoch, step = 1, -1.0, 0, 0
    history = {"train_loss": [], "val_dice": [], "epoch_time_sec": []}

    if os.path.exists(last_path):
        ck = torch.load(last_path, map_location=DEVICE, weights_only=False)
        model.load_state_dict(ck["model_state"]); opt.load_state_dict(ck["optimizer_state"])
        sched.load_state_dict(ck["scheduler_state"])
        if ema is not None: ema.load_state_dict(ck["ema_state"])
        start_epoch, best_val, best_epoch = ck["epoch"] + 1, ck["best_val_dice"], ck["best_epoch"]
        history, step = ck["history"], ck["step"]
        print(f"[{tag}] resuming from epoch {start_epoch}/{epochs}")

    if start_epoch > epochs:
        eval_model.load_state_dict(torch.load(best_path, map_location=DEVICE, weights_only=False))
        return eval_model, history

    for epoch in range(start_epoch, epochs + 1):
        t0 = time.time(); model.train(); running = 0.0
        for imgs, masks, edts, _, _ in loaders["train"]:
            imgs, masks, edts = imgs.to(DEVICE), masks.to(DEVICE), edts.to(DEVICE)
            out = model(imgs)
            if isinstance(out, tuple):                 # deep supervision
                logits, aux = out
                loss = loss_fn(logits, masks, edts)
                for w, a in zip(DS_WEIGHTS, aux):
                    loss = loss + w * loss_fn(a, masks, edts)
                loss = loss / (1.0 + sum(DS_WEIGHTS))
            else:
                loss = loss_fn(out, masks, edts)
            opt.zero_grad(); loss.backward(); opt.step()
            if ema is not None:
                ema_update(ema, model, step)
            step += 1; running += loss.item()
        sched.step()
        history["train_loss"].append(running / len(loaders["train"]))
        vd = val_dice_of(eval_model, loaders["val"])
        history["val_dice"].append(vd); history["epoch_time_sec"].append(time.time() - t0)
        print(f"[{tag}] epoch {epoch:03d}/{epochs} | loss {history['train_loss'][-1]:.4f} | "
              f"val_dice {vd:.4f} | {history['epoch_time_sec'][-1]:.1f}s")
        if vd > best_val:
            best_val, best_epoch = vd, epoch
            torch.save(eval_model.state_dict(), best_path)
        torch.save({"model_state": model.state_dict(), "optimizer_state": opt.state_dict(),
                    "scheduler_state": sched.state_dict(),
                    "ema_state": ema.state_dict() if ema is not None else None,
                    "epoch": epoch, "best_val_dice": best_val, "best_epoch": best_epoch,
                    "history": history, "step": step}, last_path)

    eval_model.load_state_dict(torch.load(best_path, map_location=DEVICE, weights_only=False))
    print(f"[{tag}] done -- best epoch {best_epoch}, val_dice {best_val:.4f}")
    return eval_model, history

